# 待处理标记，由后续段落消费
#   pb  ：下一个标题另起一页
#   gap：下一个段落增加表后留白
_PENDING = {'pb': False, 'gap': False}


def _take_gap():
    """取出并清空表后留白标记，返回要叠加到 space_before 的点数。"""
    if _PENDING['gap']:
        _PENDING['gap'] = False
        return 6
    return 0

# ---------------------------------------------------------------- 基础工具

def set_run_font(run, size=12, bold=False, name=SONG, color=None, italic=False):
    run.font.name = name
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic
    if color is not None:
        run.font.color.rgb = color
    rPr = run._element.get_or_add_rPr()
    rFonts = rPr.get_or_add_rFonts()
    for attr in ('w:ascii', 'w:hAnsi', 'w:eastAsia', 'w:cs'):
        rFonts.set(qn(attr), name)


def force_song_everywhere(doc):
    """把所有内置样式与 Normal 的字体统一为宋体。"""
    for st in doc.styles:
        try:
            st.font.name = SONG
            rPr = st.element.get_or_add_rPr()
            rFonts = rPr.get_or_add_rFonts()
            for attr in ('w:ascii', 'w:hAnsi', 'w:eastAsia', 'w:cs'):
                rFonts.set(qn(attr), SONG)
        except Exception:
            pass


def P(doc, text='', size=12, bold=False, align=None, indent=True,
      space_before=0, space_after=4, line=1.3, color=None, style=None):
    p = doc.add_paragraph(style=style)
    fmt = p.paragraph_format
    fmt.line_spacing = line
    fmt.space_before = Pt(space_before + _take_gap())
    fmt.space_after = Pt(space_after)
    if indent:
        fmt.first_line_indent = Pt(size * 2)
    if align is not None:
        p.alignment = align
    if text:
        r = p.add_run(text)
        set_run_font(r, size=size, bold=bold, color=color)
    return p


def H(doc, text, level=1):
    sizes = {1: 16, 2: 14, 3: 12, 4: 12}
    p = doc.add_heading(level=level)
    r = p.add_run(text)
    set_run_font(r, size=sizes.get(level, 12), bold=True, color=RGBColor(0, 0, 0))
    fmt = p.paragraph_format
    fmt.line_spacing = 1.3
    fmt.space_before = Pt(14 if level == 1 else (10 if level == 2 else 8))
    fmt.space_after = Pt(6)
    fmt.first_line_indent = Pt(0)
    # 消费待处理的换页标记：改为在标题上设置“段前分页”，避免产生空段落与空页
    if _PENDING['pb']:
        fmt.page_break_before = True
        _PENDING['pb'] = False
    return p


def BULLET(doc, text, size=12, level=0):
    p = doc.add_paragraph(style='List Bullet')
    # 去掉可能残留的 numbering 缩进问题，统一用悬挂缩进
    fmt = p.paragraph_format
    fmt.line_spacing = 1.3
    fmt.space_before = Pt(_take_gap())
    fmt.space_after = Pt(3)
    fmt.left_indent = Pt(size * 2 + level * size)
    fmt.first_line_indent = Pt(0)
    r = p.add_run(text)
    set_run_font(r, size=size)
    return p


def TABLE(doc, headers, rows, widths=None, font_size=10.5, caption=None):
    if caption:
        cp = doc.add_paragraph()
        cp.paragraph_format.space_before = Pt(6 + _take_gap())
        cp.paragraph_format.space_after = Pt(3)
        cp.paragraph_format.line_spacing = 1.3
        cp.paragraph_format.first_line_indent = Pt(0)
        cp.paragraph_format.keep_with_next = True
        cr = cp.add_run(caption)
        set_run_font(cr, size=10.5, bold=True)
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    hdr = t.rows[0].cells
    for i, htxt in enumerate(headers):
        hdr[i].text = ''
        p = hdr[i].paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.line_spacing = 1.0
        p.paragraph_format.space_after = Pt(2)
        r = p.add_run(htxt)
        set_run_font(r, size=font_size, bold=True)
        shade = OxmlElement('w:shd')
        shade.set(qn('w:val'), 'clear')
        shade.set(qn('w:fill'), 'EFEFEF')
        hdr[i]._tc.get_or_add_tcPr().append(shade)
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = ''
            p = cells[i].paragraphs[0]
            p.paragraph_format.line_spacing = 1.0
            p.paragraph_format.space_after = Pt(2)
            p.paragraph_format.first_line_indent = Pt(0)
            r = p.add_run(str(val))
            set_run_font(r, size=font_size)
    # 表头行跨页重复 + 行不拆分
    for row in t.rows:
        trPr = row._tr.get_or_add_trPr()
        cant = OxmlElement('w:cantSplit')
        trPr.append(cant)
    trPr = t.rows[0]._tr.get_or_add_trPr()
    th = OxmlElement('w:tblHeader')
    trPr.append(th)
    if widths:
        for row in t.rows:
            for i, w in enumerate(widths):
                row.cells[i].width = Cm(w)
    # 不在表后插入空段落：空段落会被单独挤到下一页页首，从而产生整页空白。
    # 改为记入待处理标记，由下一个段落通过 space_before 消费这段留白。
    _PENDING['gap'] = True
    return t


def CODE(doc, text, size=10):
    """用于展示公式/架构示意，使用等宽语义但字体仍为宋体以保证统一。"""
    p = doc.add_paragraph()
    fmt = p.paragraph_format
    fmt.line_spacing = 1.15
    fmt.space_before = Pt(4 + _take_gap())
    fmt.space_after = Pt(6)
    fmt.first_line_indent = Pt(0)
    fmt.left_indent = Pt(size * 2)
    r = p.add_run(text)
    set_run_font(r, size=size, bold=False)
    return p


def add_page_number_footer(section):
    footer = section.footer
    footer.is_linked_to_previous = False
    p = footer.paragraphs[0]
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.first_line_indent = Pt(0)
    r = p.add_run()
    set_run_font(r, size=10.5)
    fld1 = OxmlElement('w:fldChar'); fld1.set(qn('w:fldCharType'), 'begin')
    instr = OxmlElement('w:instrText'); instr.set(qn('xml:space'), 'preserve')
    instr.text = 'PAGE \\* arabic \\* MERGEFORMAT'
    fld2 = OxmlElement('w:fldChar'); fld2.set(qn('w:fldCharType'), 'end')
    r._r.append(fld1); r._r.append(instr); r._r.append(fld2)


def add_toc(doc):
    p = doc.add_paragraph()
    p.paragraph_format.first_line_indent = Pt(0)
    p.paragraph_format.line_spacing = 1.3
    r = p.add_run()
    set_run_font(r, size=12)
    fld1 = OxmlElement('w:fldChar'); fld1.set(qn('w:fldCharType'), 'begin')
    instr = OxmlElement('w:instrText'); instr.set(qn('xml:space'), 'preserve')
    instr.text = 'TOC \\o "1-3" \\h \\z \\u'
    fld2 = OxmlElement('w:fldChar'); fld2.set(qn('w:fldCharType'), 'separate')
    t = OxmlElement('w:t')
    t.text = '【请在 Word 中右键此处，选择“更新域”→“更新整个目录”以生成页码】'
    fld3 = OxmlElement('w:fldChar'); fld3.set(qn('w:fldCharType'), 'end')
    for e in (fld1, instr, fld2, t, fld3):
        r._r.append(e)


def hr(doc):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(2)
    p.paragraph_format.space_after = Pt(8)
    p.paragraph_format.first_line_indent = Pt(0)
    pPr = p._p.get_or_add_pPr()
    pbdr = OxmlElement('w:pBdr')
    bottom = OxmlElement('w:bottom')
    bottom.set(qn('w:val'), 'single')
    bottom.set(qn('w:sz'), '8')
    bottom.set(qn('w:color'), '888888')
    pbdr.append(bottom)
    pPr.append(pbdr)


def page_break(doc=None):
    """标记下一个标题另起一页。

    不产生空段落：由 H() 消费该标记并设置 paragraph_format.page_break_before，
    这可以避免 Word 中出现空行与空白页。
    """
    _PENDING['pb'] = True


def set_page_start(section, start=1):
    """设置该节页码从指定数字开始。"""
    sectPr = section._sectPr
    pgNumType = OxmlElement('w:pgNumType')
    pgNumType.set(qn('w:start'), str(start))
    cols = sectPr.find(qn('w:cols'))
    if cols is not None:
        cols.addprevious(pgNumType)
    else:
        sectPr.append(pgNumType)


def enable_update_fields(doc):
    """让 Word 打开文档时提示更新目录域，从而自动生成页码。"""
    settings = doc.settings.element
    uf = OxmlElement('w:updateFields')
    uf.set(qn('w:val'), 'true')
    settings.append(uf)


