"""After browser_smoke.py and a server restart, verify persisted results in the UI."""
import json
from pathlib import Path
import re
import zipfile
from playwright.sync_api import sync_playwright
from browser_smoke import BASE, BROWSER, QA, ROOT, ready, download


def main():
    previous=json.loads((QA/'browser-verification.json').read_text(encoding='utf-8'))
    fixture=previous['persistence_fixture']
    errors=[]
    with sync_playwright() as p:
        browser=p.chromium.launch(executable_path=BROWSER,headless=True,
                                  args=['--enable-unsafe-swiftshader','--use-angle=swiftshader'])
        page=browser.new_page(viewport={'width':1440,'height':1000})
        page.on('pageerror',lambda e:errors.append(str(e)))
        samples=page.request.get(BASE+'/api/samples').json()['samples']
        model=next(m for m in samples if m['id']==fixture['model_id'])
        history=page.request.get(BASE+'/api/history?model_id='+model['id']).json()['history']
        assert any(item['result_id']==fixture['result_id'] for item in history)
        page.goto(BASE,wait_until='networkidle')
        page.get_by_role('button',name=re.compile(re.escape(model['title']))).last.click()
        page.get_by_role('button',name='历史记录',exact=True).click()
        page.locator('.history-list>button').first.click()
        ready(page)
        page.get_by_label('历史结果下载').wait_for()
        bundle=download(page,'下载历史结果包','restored-assembly.zip')
        with zipfile.ZipFile(bundle) as archive:
            assert archive.testzip() is None
            report=json.loads(archive.read('report.json'))
            assert report['result_id']==fixture['result_id']
        page.screenshot(path=str(QA/'history-restored.png'),full_page=True)
        page.set_viewport_size({'width':390,'height':844})
        assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth')
        page.screenshot(path=str(QA/'mobile-history.png'),full_page=True)
        # Remove only the fixture generated by the browser test, preserving files/history.
        page.get_by_role('button',name='从列表移除',exact=True).click()
        page.get_by_role('heading',name=re.compile('花枝彩绘墙板')).wait_for()
        assert (ROOT/'runtime/imports'/(model['id']+'.glb')).exists()
        assert (ROOT/'runtime/outputs'/(fixture['result_id']+'.glb')).exists()
        assert not errors,errors
        browser.close()
    (QA/'persistence-verification.json').write_text(json.dumps({
        'status':'passed','model_restored':True,'history_restored':True,
        'restored_download_verified':True,'mobile_no_horizontal_overflow':True,
        'archived_source_preserved':True,'browser_errors':errors,
        'model_id':fixture['model_id'],'result_id':fixture['result_id'],
    },ensure_ascii=False,indent=2),encoding='utf-8')
    print('Persistence, history downloads, narrow layout and archive preservation: passed')


if __name__=='__main__':
    main()
